import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { isLocalSupabaseUrl, parseLocalStatusJson } from "./lib/supabase-local.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_LOCAL_PATH = path.join(ROOT, ".env.local");

function parseArgs(argv) {
  return {
    force: argv.includes("--force"),
    help: argv.includes("--help") || argv.includes("-h"),
  };
}

function readLocalStatus() {
  let raw;
  try {
    raw = execSync("supabase status -o json", {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (error) {
    const message = String(error.stderr ?? error.message ?? error);
    throw new Error(`Failed to read local Supabase status. Is Docker running?\n${message}`);
  }

  const status = parseLocalStatusJson(raw);
  if (!status?.API_URL) {
    throw new Error("Could not parse local Supabase status. Run `supabase start` first.");
  }
  return status;
}

function buildEnvLocalContent(status) {
  const publishableKey = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
  if (!publishableKey) {
    throw new Error("Local Supabase status is missing publishable/anon key.");
  }

  if (!isLocalSupabaseUrl(status.API_URL)) {
    throw new Error(
      `Refusing to write .env.local: API_URL is not local (${status.API_URL}). ` +
        "This guard prevents accidentally syncing a remote project into .env.local.",
    );
  }

  const lines = [
    "# Generated by npm run supabase:sync-env — local Docker Supabase only",
    `VITE_SUPABASE_URL=${status.API_URL}`,
    `VITE_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
    "SUPABASE_TARGET=local",
    "",
  ];

  if (status.DB_URL) {
    lines.splice(lines.length - 1, 0, `SUPABASE_DB_URL=${status.DB_URL}`);
  }

  return `${lines.join("\n")}\n`;
}

function diffLines(before, after) {
  const oldLines = before.split(/\r?\n/);
  const newLines = after.split(/\r?\n/);
  const max = Math.max(oldLines.length, newLines.length);
  const changes = [];

  for (let i = 0; i < max; i += 1) {
    const left = oldLines[i] ?? "";
    const right = newLines[i] ?? "";
    if (left !== right) {
      changes.push(`- ${left}`);
      changes.push(`+ ${right}`);
    }
  }

  return changes;
}

function printHelp() {
  console.log(`Usage: npm run supabase:sync-env [-- --force]

Reads local Supabase credentials from \`supabase status -o json\` and writes .env.local.

Safety:
  - Only allows local URLs (127.0.0.1 / localhost)
  - Skips write if .env.local exists unless --force is passed
  - Shows a diff when the file already exists`);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    printHelp();
    return;
  }

  const status = readLocalStatus();
  const nextContent = buildEnvLocalContent(status);

  if (!fs.existsSync(ENV_LOCAL_PATH)) {
    fs.writeFileSync(ENV_LOCAL_PATH, nextContent, "utf8");
    console.log(`Created ${path.relative(ROOT, ENV_LOCAL_PATH)}`);
    console.log(`VITE_SUPABASE_URL=${status.API_URL}`);
    return;
  }

  const currentContent = fs.readFileSync(ENV_LOCAL_PATH, "utf8");
  if (currentContent === nextContent) {
    console.log(`${path.relative(ROOT, ENV_LOCAL_PATH)} is already up to date.`);
    return;
  }

  const changes = diffLines(currentContent, nextContent);
  console.log(`${path.relative(ROOT, ENV_LOCAL_PATH)} differs from local Supabase status:\n`);
  for (const line of changes) console.log(line);
  console.log("");

  if (!args.force) {
    console.log("No changes written. Re-run with --force to overwrite:");
    console.log("  npm run supabase:sync-env -- --force");
    process.exitCode = 1;
    return;
  }

  fs.writeFileSync(ENV_LOCAL_PATH, nextContent, "utf8");
  console.log(`Updated ${path.relative(ROOT, ENV_LOCAL_PATH)}`);
}

main();
